#!/usr/bin/env bash
# Rebuilds public/punto.css from the Punto design system (aitorru/desing) at a git ref.
# Usage: scripts/sync-punto.sh [ref]   (default: origin/main; DESIGN_REPO overrides the checkout)
set -euo pipefail
REPO="${DESIGN_REPO:-/data/aitor/src/desing}"
REF="${1:-origin/main}"
OUT="$(dirname "$0")/../public/punto.css"
git -C "$REPO" fetch -q origin || echo "warning: fetch failed, using local refs" >&2
SHA="$(git -C "$REPO" rev-parse --short "$REF")"
{
  echo "/* Punto — generated by scripts/sync-punto.sh from aitorru/desing @ $SHA ($REF). Do not edit. */"
  for f in src/tokens/tokens.css src/tokens/v2.css; do
    echo "/* ── $f ── */"; git -C "$REPO" show "$REF:$f"
  done
  git -C "$REPO" ls-tree -r --name-only "$REF" src/components | grep '\.css$' | sort | while read -r f; do
    echo "/* ── $f ── */"; git -C "$REPO" show "$REF:$f"
  done
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "$SHA" > "$(dirname "$0")/../public/punto.version"
echo "public/punto.css ← $REF ($SHA), $(wc -l < "$OUT") lines"
